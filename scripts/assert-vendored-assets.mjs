#!/usr/bin/env node
/**
 * Build-time guard for the assets the app loads by URL at runtime.
 *
 * Nothing in these paths is reachable by the bundler, so a missing file is not
 * a build error — it is a 404 in front of a user, and usually an opaque one
 * (the 404 HTML gets parsed as JS and surfaces as a SyntaxError). On a
 * network-isolated deployment there is no CDN to fall back to, which turns
 * every one of these into a feature that is simply gone. Fail the build here
 * instead, with a message that says which command puts the file back.
 *
 * Two kinds of asset live under `public/vendor`:
 *
 *   - generated by `postinstall` and gitignored (the PPTX parser bundle and the
 *     pdf.js worker that rides along with it);
 *   - committed to git (KaTeX), because regenerating it needs the npm package
 *     and a closed-network checkout should not depend on that.
 *
 * Both fail the same way at runtime, so both are checked the same way here.
 */
import { stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** @type {{ file: string, what: string, fix: string }[]} */
const REQUIRED = [
  {
    file: 'public/vendor/maic-importer/index.js',
    what: 'PPTX parser bundle, loaded via /vendor/maic-importer/index.js',
    fix: 'pnpm --filter @openmaic/importer build && pnpm run sync:maic-importer',
  },
  {
    // Points GlobalWorkerOptions.workerSrc in @openmaic/importer's
    // mediaWebConvert. Without it, EMF vector artwork in an imported .pptx
    // silently fails to convert.
    file: 'public/vendor/maic-importer/pdf.worker.min.mjs',
    what: 'pdf.js worker for EMF conversion in the PPTX importer',
    fix: 'pnpm run sync:maic-importer',
  },
  {
    // Committed, not generated: interactive scenes render maths with it.
    file: 'public/vendor/katex/katex.min.js',
    what: 'KaTeX runtime for interactive scenes',
    fix: 'pnpm run gen:katex-runtime',
  },
  {
    file: 'public/vendor/katex/katex.min.css',
    what: 'KaTeX stylesheet (rewritten to use the locally vendored fonts)',
    fix: 'pnpm run gen:katex-runtime',
  },
];

const missing = [];

for (const asset of REQUIRED) {
  try {
    const info = await stat(path.join(root, asset.file));
    if (!info.isFile() || info.size === 0) throw new Error('present but not a non-empty file');
  } catch {
    missing.push(asset);
  }
}

if (missing.length > 0) {
  console.error('');
  for (const asset of missing) {
    console.error(`[assert-vendored] Missing: ${asset.file}`);
    console.error(`[assert-vendored]   ${asset.what}`);
    console.error(`[assert-vendored]   Fix: ${asset.fix}`);
  }
  console.error('[assert-vendored] (a normal `pnpm install` runs the postinstall sync).');
  console.error('');
  process.exit(1);
}

console.log(`[assert-vendored] ok: ${REQUIRED.length} runtime assets present`);
