/**
 * Vendors the KaTeX browser runtime that GENERATED INTERACTIVE SCENES load.
 *
 *   pnpm run gen:katex-runtime
 *
 * Why this exists: `postProcessInteractiveHtml` used to inject three
 * `<script>`/`<link>` tags pointing at `cdn.jsdelivr.net`. In a
 * network-isolated deployment those never load, so every formula in every
 * generated scene renders as raw `$...$` — in the app, not only in exports.
 *
 * The fonts are NOT copied here. `generate-video-export-katex.mjs` already
 * vendors the same 25 woff2 files to `public/vendor/video-export/fonts/`, and
 * a second 2 MB copy of identical bytes helps nobody. The emitted stylesheet
 * points at that directory; this script fails loudly if it is missing rather
 * than emitting CSS whose fonts 404.
 */
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');

const katexDir = path.dirname(require.resolve('katex/package.json'));
const katexVersion = require('katex/package.json').version;

/** Where `generate-video-export-katex.mjs` puts the woff2 files. */
const FONT_DIR = path.join(root, 'public', 'vendor', 'video-export', 'fonts');
const FONT_BASE_URL = '/vendor/video-export/fonts';

const OUT_DIR = path.join(root, 'public', 'vendor', 'katex');

if (!existsSync(FONT_DIR)) {
  console.error(
    `[katex-runtime] ${path.relative(root, FONT_DIR)} is missing.\n` +
      '  Run `pnpm run gen:video-export-katex` first — it vendors the woff2 files\n' +
      '  this stylesheet points at. Emitting CSS whose fonts 404 would render\n' +
      '  formulas in fallback glyphs, which is harder to notice than no CSS at all.',
  );
  process.exit(1);
}

mkdirSync(OUT_DIR, { recursive: true });

copyFileSync(path.join(katexDir, 'dist', 'katex.min.js'), path.join(OUT_DIR, 'katex.min.js'));
copyFileSync(
  path.join(katexDir, 'dist', 'contrib', 'auto-render.min.js'),
  path.join(OUT_DIR, 'auto-render.min.js'),
);

// Upstream CSS lists three formats per face — woff2, woff, ttf — and only the
// woff2 files are vendored. Keep just that one: every browser this ships to
// supports woff2, and leaving the fallbacks in would point at files that are
// not there, turning each face into a 404 before the browser gives up and uses
// the format it was going to use anyway.
const sourceCss = readFileSync(path.join(katexDir, 'dist', 'katex.min.css'), 'utf8');
const woff2Only = sourceCss.replaceAll(/src:([^;}]+)/g, (whole, sources) => {
  const woff2 = sources
    .split(/,(?![^(]*\))/)
    .map((entry) => entry.trim())
    .find((entry) => /\.woff2\)/.test(entry));
  return woff2 ? `src:${woff2}` : whole;
});

// The stylesheet lives in a different directory from the fonts, so the
// upstream `url(fonts/NAME.woff2)` has to become an absolute app path.
const css = woff2Only.replaceAll(/url\(fonts\/([^)]+)\)/g, `url(${FONT_BASE_URL}/$1)`);

const remaining = [...css.matchAll(/url\((?!\/vendor\/)[^)]*\)/g)].map((match) => match[0]);
if (remaining.length > 0) {
  console.error(
    `[katex-runtime] ${remaining.length} url() reference(s) were not rewritten and would ` +
      `resolve against the page instead of the vendored fonts: ${remaining.slice(0, 3).join(', ')}`,
  );
  process.exit(1);
}

writeFileSync(
  path.join(OUT_DIR, 'katex.min.css'),
  `/* KaTeX ${katexVersion} — GENERATED by scripts/generate-katex-runtime.mjs.\n` +
    `   Font URLs rewritten to ${FONT_BASE_URL}. Do not edit by hand. */\n${css}`,
);

copyFileSync(path.join(katexDir, 'LICENSE'), path.join(OUT_DIR, 'LICENSE'));

console.log(
  `[katex-runtime] vendored KaTeX ${katexVersion} → public/vendor/katex ` +
    `(fonts referenced from ${FONT_BASE_URL})`,
);
